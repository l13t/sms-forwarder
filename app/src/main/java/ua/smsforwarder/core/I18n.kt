/** Locale selection shared by the UI, event sources, and delivery diagnostics. */
object I18n {
    @Volatile var language: String = resolve("system")
        private set

    fun resolve(preference: String, systemLanguage: String = Locale.getDefault().language): String = when (preference) {
        "en", "uk" -> preference
        else -> if (systemLanguage == "uk") "uk" else "en"
    }
    fun setPreference(preference: String, systemLanguage: String = Locale.getDefault().language) {
        language = resolve(preference, systemLanguage)
    }
    fun text(message: Message, vararg args: Any?): String {
        val selected = language
        val template = if (selected == "uk") message.ukrainian else message.english
        return if (args.isEmpty()) template else String.format(Locale.forLanguageTag(selected), template, *args)
    }
    /** Historic diagnostics are rendered in the current language without rewriting delivery payloads. */
    fun localizeSaved(value: String): String {
        val message = Message.values().firstOrNull { it.english == value || it.ukrainian == value }
        return if (message == null) value else text(message)
    }
}

fun tr(message: Message, vararg args: Any?): String = I18n.text(message, *args)
